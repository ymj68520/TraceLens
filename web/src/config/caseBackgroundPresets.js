/** 按 id 取预设 */
export function getPresetById(id) {
  return CASE_BACKGROUND_PRESETS.find((p) => p.id === id) || null;
}

/**
 * 判断当前文本是否与某个预设的正文完全一致。
 * 用于「用户选了预设后又手工改过」时回退为自定义状态。
 */
export function matchPresetId(text) {
  const normalized = (text || '').trim();
  if (!normalized) return '';
  const hit = CASE_BACKGROUND_PRESETS.find((p) => p.background === normalized);
  return hit ? hit.id : '';
}

/** 按分组返回预设，保持 PRESET_GROUPS 的顺序 */
export function presetsByGroup() {
  return PRESET_GROUPS.map((group) => ({
    ...group,
    presets: CASE_BACKGROUND_PRESETS.filter((p) => p.group === group.key),
  })).filter((g) => g.presets.length > 0);
}
