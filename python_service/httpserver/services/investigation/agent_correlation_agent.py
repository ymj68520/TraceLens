"""CorrelationAgent — first semantic correlation pass (P5B §20-§25, §46).

Runs ONLY when a real relation question exists AND the
DeterministicCorrelationEngine has already produced bounded candidates;
never a whole-case auto-start (§20). Its input is the frozen
``CorrelationContextPackV1`` — bounded candidates, occurrence digests,
evidence refs — never the full case graph or full evidence set (§21).

Its output is a semantic ``CorrelationProposalV1``: a PROPOSAL, never a
canonical relation (§22). Hard causality boundary (§23):
``temporal proximity != causality``; a causal reading may only surface as
``causal_hypothesis`` with ``assertion_class = HYPOTHESIS``;
``causal_confirmed`` does not exist in the output vocabulary. Every
evidence ref in the proposal must be inside the context allowlist (§62).

Entering the claim pipeline (§24) always goes
CorrelationProposal -> ProposedClaimV1 -> Grounding -> SupportBundle ->
SemanticVerifier -> AssertionPolicy; grounding is never skipped.
"""

from __future__ import annotations

import hashlib
import enum
from typing import Any, Mapping, Optional

from pydantic import BaseModel, ConfigDict, model_validator

from .agent_claims import ProposedClaimV1
from .agent_correlation import CausalStatus, CorrelationCandidateV1
from .agent_entities import EntityOccurrenceV1
from .agent_runtime import canonical_state_json
from .agent_specialist_result import AssertionClass

CORRELATION_CONTEXT_VERSION = "correlation-context:v1"
CORRELATION_PROPOSAL_VERSION = "correlation-proposal:v1"
CORRELATION_AGENT_PROMPT_VERSION = "correlation-agent:v1"


class CorrelationContextPackV1(BaseModel):
    """§21 frozen CorrelationAgent input — bounded by construction."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    context_version: str = CORRELATION_CONTEXT_VERSION

    task_id: str
    investigation_id: str

    question: str
    source_scope_ids: tuple[str, ...] = ()

    # bounded deterministic candidates (already generated by the engine)
    correlation_candidates: tuple[CorrelationCandidateV1, ...] = ()

    # occurrence digests for the candidate endpoints (ids + values only)
    occurrence_digests: tuple[Mapping[str, str], ...] = ()

    evidence_allowlist: tuple[str, ...] = ()

    limitations: tuple[str, ...] = ()

    # §21: normally empty — the pack is the whole input
    allowed_tool_ids: tuple[str, ...] = ()

    context_hash: str = ""

    @model_validator(mode="before")
    @classmethod
    def _canonicalize(cls, data):
        if not isinstance(data, dict):
            return data
        data["question"] = str(data.get("question") or "").strip()
        data["evidence_allowlist"] = tuple(sorted({
            str(ref) for ref in (data.get("evidence_allowlist") or ()) if ref
        }))
        data["source_scope_ids"] = tuple(sorted({
            str(ref) for ref in (data.get("source_scope_ids") or ()) if ref
        }))
        candidates = tuple(data.get("correlation_candidates") or ())
        digests = tuple(data.get("occurrence_digests") or ())
        payload = {
            "context_version": CORRELATION_CONTEXT_VERSION,
            "task_id": data.get("task_id"),
            "investigation_id": data.get("investigation_id"),
            "question": data["question"],
            "source_scope_ids": list(data["source_scope_ids"]),
            "candidate_ids": sorted(
                candidate.correlation_id for candidate in candidates
            ),
            "occurrence_ids": sorted(
                str(digest.get("occurrence_id", "")) for digest in digests
            ),
            "evidence_allowlist": list(data["evidence_allowlist"]),
        }
        data["correlation_candidates"] = candidates
        data["occurrence_digests"] = digests
        data["context_hash"] = hashlib.sha256(
            canonical_state_json(payload).encode("utf-8")
        ).hexdigest()
        return data


class CorrelationProposalV1(BaseModel):
    """§22 semantic correlation output — always a proposal."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    proposal_version: str = CORRELATION_PROPOSAL_VERSION

    proposal_id: str
    subject_ref: str
    object_ref: str
    relation_family: str

    assertion_class: AssertionClass

    evidence_refs: tuple[str, ...] = ()

    semantic_interpretation: str
    alternative_explanations: tuple[str, ...] = ()
    limitations: tuple[str, ...] = ()

    causal_status: CausalStatus = CausalStatus.NOT_ASSESSED

    # runtime-bound, never model-controlled:
    task_id: str = ""
    investigation_id: str = ""
    context_hash: str = ""
    model: Optional[str] = None
    prompt_version: str = CORRELATION_AGENT_PROMPT_VERSION
    input_hash: str = ""


class CorrelationOutputViolationCode(str, enum.Enum):
    CORRELATION_VERSION_UNSUPPORTED = "CORRELATION_VERSION_UNSUPPORTED"
    CORRELATION_IDENTITY_MISMATCH = "CORRELATION_IDENTITY_MISMATCH"
    CORRELATION_CANDIDATE_MISMATCH = "CORRELATION_CANDIDATE_MISMATCH"
    CORRELATION_TEMPORAL_CAUSAL_FORBIDDEN = (
        "CORRELATION_TEMPORAL_CAUSAL_FORBIDDEN"
    )
    CORRELATION_CAUSAL_REQUIRES_HYPOTHESIS = (
        "CORRELATION_CAUSAL_REQUIRES_HYPOTHESIS"
    )
    CORRELATION_EVIDENCE_REF_OUTSIDE_ALLOWLIST = (
        "CORRELATION_EVIDENCE_REF_OUTSIDE_ALLOWLIST"
    )
    CORRELATION_TEXT_INVALID = "CORRELATION_TEXT_INVALID"




class CorrelationOutputValidator:
    """Deterministic output gate (§23/§62). Any violation = fail closed."""

    def validate(
        self,
        proposal: CorrelationProposalV1,
        *,
        context: CorrelationContextPackV1,
    ) -> tuple[CorrelationOutputViolationCode, ...]:
        violations: list[CorrelationOutputViolationCode] = []
        if proposal.proposal_version != CORRELATION_PROPOSAL_VERSION:
            violations.append(
                CorrelationOutputViolationCode.
                CORRELATION_VERSION_UNSUPPORTED
            )
        if (
            proposal.context_hash
            and proposal.context_hash != context.context_hash
        ):
            violations.append(
                CorrelationOutputViolationCode.CORRELATION_IDENTITY_MISMATCH
            )
        candidate_ids = {
            candidate.correlation_id
            for candidate in context.correlation_candidates
        }
        if proposal.proposal_id not in candidate_ids:
            violations.append(
                CorrelationOutputViolationCode.CORRELATION_CANDIDATE_MISMATCH
            )
        # §23: temporal-only relations are never causal, and any causal
        # reading is a HYPOTHESIS. causal_confirmed is unconstructible.
        if proposal.relation_family == "temporal_overlap":
            if proposal.causal_status is not CausalStatus.NOT_ASSESSED:
                violations.append(
                    CorrelationOutputViolationCode.
                    CORRELATION_TEMPORAL_CAUSAL_FORBIDDEN
                )
            if proposal.assertion_class is not AssertionClass.HYPOTHESIS:
                violations.append(
                    CorrelationOutputViolationCode.
                    CORRELATION_TEMPORAL_CAUSAL_FORBIDDEN
                )
        if proposal.causal_status is CausalStatus.CAUSAL_HYPOTHESIS:
            if proposal.assertion_class is not AssertionClass.HYPOTHESIS:
                violations.append(
                    CorrelationOutputViolationCode.
                    CORRELATION_CAUSAL_REQUIRES_HYPOTHESIS
                )
        allowlist = set(context.evidence_allowlist)
        for ref in proposal.evidence_refs:
            if ref not in allowlist:
                violations.append(
                    CorrelationOutputViolationCode.
                    CORRELATION_EVIDENCE_REF_OUTSIDE_ALLOWLIST
                )
        if not proposal.semantic_interpretation.strip():
            violations.append(
                CorrelationOutputViolationCode.CORRELATION_TEXT_INVALID
            )
        return tuple(violations)


class CorrelationAgentFailure(BaseModel):
    """§19-style explicit runtime failure; never a semantic status."""

    model_config = ConfigDict(frozen=True)

    failure_code: str
    detail: str = ""
    model: Optional[str] = None


class CorrelationAgent:
    """PydanticAI agent over the frozen bounded context (§46: reuses the
    frozen-envelope / model-adapter / typed-output / failure-normalization
    pattern; no second provider client)."""

    VERSION = CORRELATION_AGENT_PROMPT_VERSION

    def __init__(
        self,
        *,
        model: Optional[Any] = None,
        model_name: Optional[str] = None,
        retries: int = 1,
    ):
        self._model = model
        self._model_name = model_name
        self._retries = retries

    @property
    def instructions(self) -> str:
        return (
            "You are a forensic correlation interpretation agent. You "
            "receive a frozen, bounded set of deterministic correlation "
            "candidates plus occurrence digests. For the requested "
            "candidate, produce a semantic interpretation: what relation "
            "the exposed evidence supports, plausible alternative "
            "explanations, and limitations. Temporal proximity is NEVER "
            "causality: a causal reading is always a HYPOTHESIS with "
            "causal_status=causal_hypothesis, and never causal_confirmed. "
            "Cite only evidence refs from the provided allowlist. Your "
            "output is a proposal, not a conclusion."
        )

    def _build_agent(self):
        from pydantic_ai import Agent

        if self._model is not None:
            return Agent(
                self._model,
                instructions=self.instructions,
                output_type=CorrelationProposalV1,
                retries=self._retries,
            )
        return Agent(
            self.instructions,
            output_type=CorrelationProposalV1,
            retries=self._retries,
        )

    async def run(
        self,
        context: CorrelationContextPackV1,
        *,
        candidate: CorrelationCandidateV1,
        model_output: Optional[Mapping[str, Any]] = None,
    ) -> CorrelationProposalV1 | CorrelationAgentFailure:
        """Interpret one bounded candidate. The raw model output is
        validated against the frozen context first (fail closed), then
        runtime facts are bound (never model-controlled). Tests may pass
        ``model_output`` directly to exercise the gate deterministically."""
        if model_output is not None:
            try:
                raw = CorrelationProposalV1(**model_output)
            except Exception as exc:
                return CorrelationAgentFailure(
                    failure_code="output_invalid",
                    detail=f"{type(exc).__name__}: {exc}"[:500],
                    model=self._model_name,
                )
        else:
            from .agent_specialist_executor import map_provider_exception

            try:
                agent = self._build_agent()
                run_result = await agent.run(_render_context(context, candidate))
                raw = run_result.output
            except Exception as exc:
                try:
                    mapped = map_provider_exception(exc).value
                except Exception:
                    mapped = "agent_internal_failure"
                return CorrelationAgentFailure(
                    failure_code=mapped,
                    detail=f"{type(exc).__name__}: {exc}"[:500],
                    model=self._model_name,
                )

        # Validate the RAW model output (keep the echoed proposal_id so a
        # model interpreting the wrong candidate fails closed), then bind
        # runtime facts - never model-controlled.
        bound = raw.model_copy(update={
            "task_id": context.task_id,
            "investigation_id": context.investigation_id,
            "context_hash": context.context_hash,
            "model": self._model_name,
            "prompt_version": self.VERSION,
            "input_hash": context.context_hash,
        })
        violations = CorrelationOutputValidator().validate(bound, context=context)
        if violations:
            return CorrelationAgentFailure(
                failure_code="output_invalid",
                detail=",".join(code.value for code in violations),
                model=self._model_name,
            )
        return bound.model_copy(update={
            "proposal_id": candidate.correlation_id,
        })


def _render_context(
    context: CorrelationContextPackV1,
    candidate: CorrelationCandidateV1,
) -> str:
    lines = [
        f"question: {context.question}",
        f"candidate: {candidate.correlation_id}",
        f"relation_family: {candidate.relation_family}",
        f"derivation: {candidate.derivation.value}",
        f"subject: {candidate.subject_ref}",
        f"object: {candidate.object_ref}",
        "evidence_allowlist: " + (
            ", ".join(context.evidence_allowlist) or "(none)"
        ),
    ]
    for digest in context.occurrence_digests:
        if digest.get("occurrence_id") in (
            candidate.subject_ref, candidate.object_ref
        ):
            lines.append(
                f"occurrence {digest.get('occurrence_id')}: "
                f"{digest.get('entity_type')}={digest.get('normalized_value')} "
                f"(namespace={digest.get('namespace')})"
            )
    for limitation in context.limitations:
        lines.append(f"limitation: {limitation}")
    return "\n".join(lines)


def proposal_to_claim(
    proposal: CorrelationProposalV1,
    *,
    task_id: str,
    investigation_id: str,
) -> ProposedClaimV1:
    """§24 seam: a semantic correlation proposal enters the claim pipeline
    as a ProposedClaimV1 — grounding, support bundle, semantic verifier
    and the assertion policy all still apply downstream."""
    return ProposedClaimV1(
        task_id=task_id,
        investigation_id=investigation_id,
        proposal_id="",  # derived
        text=proposal.semantic_interpretation,
        assertion_class=proposal.assertion_class,
        evidence_refs=proposal.evidence_refs,
        source_candidate_id=proposal.proposal_id,
        relationship_refs=(proposal.proposal_id,),
        limitations=proposal.limitations,
        normalization_warnings=(),
        input_hash="",  # derived
    )


