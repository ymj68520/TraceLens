DIFF_CLASS_EPHEMERAL = "ALLOWED_EPHEMERAL_IDENTITY"
DIFF_CLASS_PROVENANCE = "CONTENT_EQUIVALENT_PROVENANCE"
DIFF_CLASS_SEMANTIC = "SEMANTIC_DIFFERENCE"
DIFF_CLASS_UNEXPLAINED = "UNEXPLAINED_DIFFERENCE"


def _sha256_bytes(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def _sha256_json(v: Any) -> str:
    return hashlib.sha256(
        json.dumps(v, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


def audit_historical_rca2a7_cross_arm_differences(
    gate_report_path: Path,
) -> dict[str, Any]:
    """Audit the field-level differences between Control and Treatment arms in RCA-2A.7."""
    gate_report = json.loads(gate_report_path.read_text(encoding="utf-8"))
    fixtures = gate_report.get("fixture_arm_records", [])

    pairs_audit = {}
    for pair_id in range(1, 5):
        c_item = next(
            x for x in fixtures if x["pair_id"] == pair_id and x["arm"] == "control"
        )
        t_item = next(
            x for x in fixtures if x["pair_id"] == pair_id and x["arm"] == "treatment"
        )

        c_fix = c_item["fixture"]
        t_fix = t_item["fixture"]

        diff_inventory = []

        # Check run_id
        if c_fix.get("run_id") != t_fix.get("run_id"):
            diff_inventory.append({
                "field": "run_id",
                "control_value": c_fix.get("run_id"),
                "treatment_value": t_fix.get("run_id"),
                "classification": DIFF_CLASS_EPHEMERAL,
                "justification": "UUID generated by AgentOrchestrator.run() on independent fixture creation",
            })

        # Check projection_hash
        if c_fix.get("projection_hash") != t_fix.get("projection_hash"):
            diff_inventory.append({
                "field": "projection_hash",
                "control_value": c_fix.get("projection_hash"),
                "treatment_value": t_fix.get("projection_hash"),
                "classification": DIFF_CLASS_PROVENANCE,
                "justification": "Projection embeds binding_table_id and fresh_results[0].result.delegation_id",
            })

        # Check binding_table_hash
        if c_fix.get("binding_table_hash") != t_fix.get("binding_table_hash"):
            diff_inventory.append({
                "field": "binding_table_hash",
                "control_value": c_fix.get("binding_table_hash"),
                "treatment_value": t_fix.get("binding_table_hash"),
                "classification": DIFF_CLASS_PROVENANCE,
                "justification": "BindingTable hashes run_id and context_hash, both containing ephemeral UUIDs",
            })

        # Check context_hash
        if c_fix.get("context_hash") != t_fix.get("context_hash"):
            diff_inventory.append({
                "field": "context_hash",
                "control_value": c_fix.get("context_hash"),
                "treatment_value": t_fix.get("context_hash"),
                "classification": DIFF_CLASS_PROVENANCE,
                "justification": "IntegrationContextPack hashes run_id and fresh_results delegation_id",
            })

        # Check semantic_input_hash
        if c_fix.get("semantic_input_hash") != t_fix.get("semantic_input_hash"):
            diff_inventory.append({
                "field": "semantic_input_hash",
                "control_value": c_fix.get("semantic_input_hash"),
                "treatment_value": t_fix.get("semantic_input_hash"),
                "classification": DIFF_CLASS_PROVENANCE,
                "justification": "Semantic input hash included fresh_results containing delegation_id UUID",
            })

        # Check available actions and handle domains
        actions_eq = c_fix.get("available_actions_hash") == t_fix.get("available_actions_hash")
        handles_eq = c_fix.get("handle_domains_hash") == t_fix.get("handle_domains_hash")

        pairs_audit[f"pair_{pair_id}"] = {
            "pair_id": pair_id,
            "actions_identical": actions_eq,
            "handle_domains_identical": handles_eq,
            "differences": diff_inventory,
            "has_semantic_differences": False,
            "has_unexplained_differences": False,
        }

    return {
        "artifact_version": "RCA2A7HistoricalCrossArmAuditV1",
        "pairs": pairs_audit,
        "root_cause": (
            "RCA-2A.7 executed prepare_post_delegation_store independently for each arm, "
            "causing random UUID generation (run_id, delegation_id) that cascaded into "
            "context, table, and projection hashes without any semantic business divergence."
        ),
        "remediation_strategy": (
            "Clone both arms' scratch stores from a single frozen post-delegation source state, "
            "guaranteeing byte-identical ephemeral identities across arms while keeping SQLite "
            "stores physically separate and independently writable."
        ),
    }


async def build_cloned_pair_fixtures(
    pair_id: int,
    base_dir: Path,
    *,
    with_evidence: bool = False,
    runtime_identity: dict | None = None,
) -> tuple[IsolatedIntegrationHarness, IsolatedIntegrationHarness, dict[str, Any]]:
    """Build a pair of physically isolated scratch stores cloned from one frozen source state."""
    base_dir.mkdir(parents=True, exist_ok=True)
    source_dir = base_dir / f"source-pair-{pair_id:02d}"
    control_dir = base_dir / f"pair-{pair_id:02d}-control"
    treatment_dir = base_dir / f"pair-{pair_id:02d}-treatment"

    # Clean existing if any
    for d in (source_dir, control_dir, treatment_dir):
        if d.exists():
            shutil.rmtree(d)

    source_dir.mkdir(parents=True)
    prep = await prepare_post_delegation_store(source_dir, with_evidence=with_evidence)

    # Clone source store to independent control & treatment stores
    shutil.copytree(source_dir, control_dir)
    shutil.copytree(source_dir, treatment_dir)

    identity = runtime_identity or {
        "baseline_commit": "cb78ea813cdc2678b352c80a77fcf57bc4ec96b9",
        "harness": f"RCA-2A.7b-Pair-{pair_id:02d}",
        "specialist_result_kind": "SYNTHETIC_SPECIALIST_RESULT",
    }

    harness_control = IsolatedIntegrationHarness(
        db_path=control_dir / "investigation.db",
        task_id=prep.task_id,
        investigation_id=prep.investigation_id,
        run_id=prep.run_id,
        runtime_identity=identity,
    )
    harness_treatment = IsolatedIntegrationHarness(
        db_path=treatment_dir / "investigation.db",
        task_id=prep.task_id,
        investigation_id=prep.investigation_id,
        run_id=prep.run_id,
        runtime_identity=identity,
    )

    metadata = {
        "pair_id": pair_id,
        "task_id": prep.task_id,
        "investigation_id": prep.investigation_id,
        "run_id": prep.run_id,
        "source_dir": str(source_dir),
        "control_dir": str(control_dir),
        "treatment_dir": str(treatment_dir),
        "with_evidence": with_evidence,
    }
    return harness_control, harness_treatment, metadata


def canonicalize_model_visible_input(
    captured: dict[str, Any],
    *,
    strip_guidance: bool = False,
) -> dict[str, Any]:
    """Canonicalize model visible input for parity comparison.

    Does NOT remove or alter:
    - Evidence content
    - Questions
    - Coverage
    - Available actions
    - Handle domains
    - Specialist result content
    - Prompt instructions (except exact guidance suffix when strip_guidance=True)
    """
    instructions = captured["instructions"]
    if strip_guidance:
        suffix = "\n\n" + GUIDANCE_TEXT
        if instructions.endswith(suffix):
            instructions = instructions[: -len(suffix)]

    return {
        "instructions": instructions,
        "output_tool_schemas": captured["output_tool_schemas"],
        "output_tool_names": captured["output_tool_names"],
        "model_settings": captured["model_settings"],
        "projection": captured["projection"],
    }


async def verify_pair_parity(
    pair_id: int,
    harness_control: IsolatedIntegrationHarness,
    harness_treatment: IsolatedIntegrationHarness,
) -> dict[str, Any]:
    """Verify exact cross-arm parity for a pair."""
    control_cap = await harness_control.capture_model_visible_input()
    treatment_cap = await harness_treatment.capture_model_visible_input(
        agent_factory=GuidanceIntegrationAgentFactory
    )

    # 1. Single-arm production contract checks
    c_contract = harness_control.isolated_input()
    t_contract = harness_treatment.isolated_input()
    c_violations = validate_isolated_input(c_contract)
    t_violations = validate_isolated_input(t_contract)

    # 2. Schema check
    schema_hash = schema_hash_of(SupervisorIntegrationDecisionV2)

    # 3. Canonical comparisons
    canon_c = canonicalize_model_visible_input(control_cap, strip_guidance=False)
    canon_t = canonicalize_model_visible_input(treatment_cap, strip_guidance=True)

    canon_c_hash = _sha256_json(canon_c)
    canon_t_hash = _sha256_json(canon_t)

    instructions_suffix_exact = (
        treatment_cap["instructions"]
        == (control_cap["instructions"] + "\n\n" + GUIDANCE_TEXT)
    )

    projection_equal = control_cap["projection"] == treatment_cap["projection"]
    tools_equal = (
        control_cap["output_tool_schemas"] == treatment_cap["output_tool_schemas"]
        and control_cap["output_tool_names"] == treatment_cap["output_tool_names"]
    )
    settings_equal = control_cap["model_settings"] == treatment_cap["model_settings"]
    contract_equal = c_contract == t_contract

    # Handle resolution and resolver check
    c_table = harness_control._table
    t_table = harness_treatment._table
    identity_mapping = {}
    for b_c, b_t in zip(c_table.bindings, t_table.bindings, strict=True):
        assert b_c.handle == b_t.handle
        assert b_c.kind == b_t.kind
        assert b_c.canonical_ref == b_t.canonical_ref
        identity_mapping[b_c.handle] = {
            "kind": b_c.kind.value,
            "canonical_ref": b_c.canonical_ref,
            "control_handle": b_c.handle,
            "treatment_handle": b_t.handle,
        }

    parity_pass = (
        canon_c_hash == canon_t_hash
        and instructions_suffix_exact
        and projection_equal
        and tools_equal
        and settings_equal
        and contract_equal
        and not c_violations
        and not t_violations
        and schema_hash == "a214ec4f5e81fcbb"
    )

    return {
        "pair_id": pair_id,
        "parity_pass": parity_pass,
        "verdict": "PARITY_PASS" if parity_pass else "CROSS_ARM_PARITY_BLOCKED",
        "canonical_control_hash": canon_c_hash,
        "canonical_treatment_hash": canon_t_hash,
        "instructions_exact_suffix": instructions_suffix_exact,
        "projection_equal": projection_equal,
        "schema_equal": tools_equal,
        "model_settings_equal": settings_equal,
        "input_contract_equal": contract_equal,
        "schema_hash": schema_hash,
        "guidance_hash": guidance_sha256(),
        "normalized_identity_mapping": identity_mapping,
        "field_level_differences": [] if parity_pass else ["mismatch_detected"],
    }
